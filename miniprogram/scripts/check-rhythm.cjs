const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const vm = require('node:vm');
const exportsObject = {};
const output = ts.transpileModule(fs.readFileSync('services/rhythm.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText;
vm.runInNewContext(output, { exports: exportsObject });
const { Rhythm } = exportsObject;
const timer = new Rhythm(10, 1, 'timer');
timer.start(1000);
assert.equal(timer.state(4500).value, 7);
timer.pause(5000);
assert.equal(timer.state(100000).value, 6, 'background time cannot advance a paused rhythm');
timer.start(100000);
assert.equal(timer.state(106000).finished, true);
assert.equal(timer.state(106000).value, 0);
assert.equal(timer.state(106000).progress, 100);
timer.reset();
assert.equal(timer.state(999999).value, 10);
const count = new Rhythm(12, 3, 'count');
count.start(1000);
assert.equal(count.state(4000).value, 1);
assert.equal(count.state(25000).value, 8, 'delayed event loop uses elapsed time, not number of interval callbacks');
assert.equal(count.state(37000).value, 12);
assert.equal(count.state(37000).finished, true);
console.log('Rhythm: countdown, pause/resume, reset, delayed callbacks and completion limits passed');
